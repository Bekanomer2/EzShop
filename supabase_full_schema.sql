-- 1. ТАБЛИЦА БРЕНДОВ
create table if not exists brands (
    id serial primary key,
    name text not null unique,
    country text not null default ''
);

-- 2. ТАБЛИЦА СМАРТФОНОВ
create table if not exists products (
    id serial primary key,
    name text not null,
    brand text not null,
    price numeric(12, 2) not null,
    img text not null,
    ram int not null,
    storage int not null,
    color text not null,
    display text not null,
    battery int not null,
    description text not null default '',
    in_stock boolean not null default true,
    rating double precision not null default 5.0
);

-- 3. ТАБЛИЦА ЗАКАЗОВ
create table if not exists orders (
    id bigint generated by default as identity primary key,
    user_id text,
    user_order_id bigint,
    date text,
    total numeric(12, 2) not null default 0,
    status text not null default 'В обработке',
    customer_name text not null default '',
    customer_phone text not null default '',
    customer_address text not null default '',
    items jsonb not null default '[]'::jsonb,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 4. ТАБЛИЦА ПОЗИЦИЙ ЗАКАЗА
create table if not exists order_items (
    id serial primary key,
    order_id bigint,
    product_id int,
    name text not null,
    price numeric(12, 2) not null,
    qty int not null default 1
);

-- 5. ТАБЛИЦА ОТЗЫВОВ
create table if not exists reviews (
    id bigint generated by default as identity primary key,
    product_id int not null,
    author text not null,
    text text not null,
    rating int not null default 5,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 6. ПОЛИТИКИ ДОСТУПА (Row Level Security)
alter table brands enable row level security;
alter table products enable row level security;
alter table orders enable row level security;
alter table order_items enable row level security;
alter table reviews enable row level security;

drop policy if exists "Allow all on brands" on brands;
create policy "Allow all on brands" on brands for all using (true) with check (true);

drop policy if exists "Allow all on products" on products;
create policy "Allow all on products" on products for all using (true) with check (true);

drop policy if exists "Allow all on orders" on orders;
create policy "Allow all on orders" on orders for all using (true) with check (true);

drop policy if exists "Allow all on order_items" on order_items;
create policy "Allow all on order_items" on order_items for all using (true) with check (true);

drop policy if exists "Allow all on reviews" on reviews;
create policy "Allow all on reviews" on reviews for all using (true) with check (true);

